#!/usr/bin/env python3
"""Collect per-project size statistics into data/stats.{json,js}.

For every project folder the tool counts:
  files  — all files except docs/preview.png style images are still counted,
           but only code extensions below contribute LOC
  loc    — non-blank, non-comment-only lines of code (code extensions only)
  bytes  — total size of all files in the folder

Output:
  data/stats.json — structured stats (consumed by tools & CI)
  data/stats.js   — window.AWESOME_STATS (consumed by compare.html)

Usage:
    python tools/generate_stats.py         # regenerate data files
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = REPO_ROOT / "data"
PROJECT_DIRS = [REPO_ROOT / d for d in ("bots", "web", "desktop")]
TEHRAN_TZ = timezone(timedelta(hours=3, minutes=30))

CODE_EXTS = {".py", ".js", ".php", ".java", ".cs", ".cpp", ".cc", ".h", ".ps1", ".html", ".lua", ".css", ".sql"}


def loc_of(path: Path) -> int:
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return 0
    count = 0
    for line in text.splitlines():
        stripped = line.strip()
        if stripped and not stripped.startswith(("//", "#", "/*", "*", "--", "<!--")):
            count += 1
    return count


def collect(slug_dir: Path) -> dict:
    files = 0
    loc = 0
    total_bytes = 0
    for path in slug_dir.rglob("*"):
        if path.is_file():
            files += 1
            total_bytes += path.stat().st_size
            if path.suffix.lower() in CODE_EXTS:
                loc += loc_of(path)
    return {"files": files, "loc": loc, "bytes": total_bytes}


def main() -> None:
    catalog = json.loads((DATA_DIR / "catalog.json").read_text(encoding="utf-8"))
    projects: dict[str, dict] = {}
    totals = {"files": 0, "loc": 0, "bytes": 0}
    for project in catalog["projects"]:
        slug_dir = REPO_ROOT / project["path"]
        stats = collect(slug_dir)
        projects[project["slug"]] = stats
        for key in totals:
            totals[key] += stats[key]

    payload = {
        "generated_at": datetime.now(TEHRAN_TZ).replace(microsecond=0).isoformat(),
        "totals": totals,
        "projects": projects,
    }
    json_text = json.dumps(payload, ensure_ascii=False, indent=2)
    (DATA_DIR / "stats.json").write_text(json_text + "\n", encoding="utf-8")
    (DATA_DIR / "stats.js").write_text(
        "// Auto-generated by tools/generate_stats.py — do not edit manually.\n"
        "// Regenerate with: python tools/generate_stats.py\n"
        f"window.AWESOME_STATS = {json_text};\n",
        encoding="utf-8",
    )
    print(
        f"✓ stats: {len(projects)} projects · "
        f"{totals['files']} files · {totals['loc']:,} LOC · {totals['bytes'] / 1024 / 1024:.1f} MB"
    )


if __name__ == "__main__":
    main()
