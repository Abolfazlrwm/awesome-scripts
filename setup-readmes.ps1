# 🛍 ربات فروشگاهی پیشرفته (Advanced Shop Bot)

یک فروشگاه‌ساز کامل برای تلگرام — دقیقاً شبیه یک سایت فروشگاهی حرفه‌ای، اما تمام‌وکمال داخل تلگرام. محصولات با تنوع رنگ/سایز/مدل، سبد خرید هوشمند، کوپن تخفیف، پرداخت کارت‌به‌کارت، سیستم رفرال و پنل مدیریت کامل.

![Python](https://img.shields.io/badge/python-3.8+-blue.svg)
![python-telegram-bot](https://img.shields.io/badge/python--telegram--bot-22.7+-2CA5E0.svg)
![License](https://img.shields.io/badge/license-MIT-green)

## ✨ امکانات

- 📦 کاتالوگ محصول با تنوع (واریانت): هر محصول می‌تواند چند رنگ/سایز/مدل با قیمت و موجودی جداگانه داشته باشد
- 🛒 سبد خرید هوشمند: افزودن، حذف، اعمال کوپن تخفیف، ثبت سفارش
- 💳 پرداخت کارت‌به‌کارت: ارسال رسید توسط کاربر و تأیید/رد توسط ادمین
- 🎁 سیستم ارجاع (رفرال) و پورسانت خودکار برای معرفی‌کننده‌ها
- 🎫 پشتیبانی با سیستم تیکت (ارسال و پاسخ‌گویی)
- 🧾 مشاهده‌ی تاریخچه‌ی سفارشات هر کاربر
- 🏷 کوپن‌های تخفیف درصدی یا مبلغی، با تاریخ انقضا و محدودیت تعداد استفاده
- 🎛 پنل مدیریت کامل: دسته‌بندی، محصول، واریانت، سفارشات، پرداخت‌ها، کوپن‌ها، تیکت‌ها، کاربران و آمار فروش
- 🎨 دکمه‌های رنگی (style) برای تأیید/لغو در پنل مدیریت
- 💾 پایگاه‌داده‌ی SQLite داخلی — بدون نیاز به نصب دیتابیس جداگانه

## 📋 پیش‌نیازها

- Python نسخه‌ی ۳.۸ یا بالاتر
- کتابخانه‌ی `python-telegram-bot` نسخه‌ی ۲۲.۷ یا جدیدتر

## ⚙️ نصب و راه‌اندازی

### گام ۱: نصب وابستگی‌ها
```bash
pip install -r requirements.txt

### گام ۲: تنظیم توکن و ادمین
فایل `bot.py` را باز کن و این دو مقدار را در ابتدای فایل تغییر بده:

| متغیر | توضیح | نمونه |
|---|---|---|
| `BOT_TOKEN` | توکن ربات از [@BotFather](https://t.me/BotFather) | `123456:ABC-DEF1234ghIkl...` |
| `ADMIN_IDS` | لیست آیدی عددی مدیران، از [@userinfobot](https://t.me/userinfobot) بگیر | `[123456789]` |

می‌توانی چند ادمین هم اضافه کنی:
```python
ADMIN_IDS = [123456789, 987654321]

### گام ۳: اجرا
```bash
python bot.py

پایگاه‌داده (`shop_advanced.db`) به‌صورت خودکار در همان پوشه ساخته می‌شود.

### گام ۴: تنظیمات اولیه‌ی فروشگاه
پس از اجرای ربات:
1. با آیدی ادمین وارد ربات شو و `/admin` را بزن
2. از پنل مدیریت، دسته‌بندی → محصول → واریانت (رنگ/سایز/قیمت/موجودی) اضافه کن
3. شماره کارت پرداخت را در تابع `payment_start` داخل کد (متغیر `card_number`) تنظیم کن

## 🖥 اجرای دائمی روی سرور (اختیاری)

برای اینکه ربات بعد از بستن ترمینال هم روشن بماند:
```bash
screen -S shopbot
python bot.py

سپس با `Ctrl+A` و بعد `D` از screen خارج شو؛ ربات در پس‌زمینه اجرا می‌ماند.

## 📁 ساختار پایگاه‌داده

پایگاه‌داده شامل جداول: `categories`, `products`, `product_variants`, `cart_items`, `orders`, `order_items`, `users`, `wallet_transactions`, `coupons`, `support_tickets`, `payments` است — همگی به‌صورت خودکار ساخته می‌شوند.

