ربات مدیریت چند اکانت تلگرام از طریق Telethon. با افزودن اکانت‌های خودت به ربات، می‌توانی به‌صورت خودکار با آن‌ها به گروه/کانال جوین بزنی یا روی پست‌ها ری‌اکشن ثبت کنی.

![Python](https://img.shields.io/badge/python-3.8+-blue.svg)
![Telethon](https://img.shields.io/badge/Telethon-latest-2CA5E0.svg)
![License](https://img.shields.io/badge/license-MIT-green)

## ✨ امکانات

- ➕ افزودن اکانت تلگرام به ربات (با کد تأیید و در صورت نیاز رمز دو مرحله‌ای)
- 🚀 جوین گروهی خودکار با چند اکانت به یک لینک مشخص
- ❤️ ثبت ری‌اکشن دلخواه (هر ایموجی) روی یک پست مشخص با چند اکانت
- 🔢 انتخاب تعداد اکانت مورد استفاده برای هر عملیات
- 📋 لیست اکانت‌های اضافه‌شده با شماره و شناسه
- 🗑 حذف اکانت از لیست با وارد کردن شناسه
- 💾 ذخیره‌ی امن اطلاعات نشست (session) در فایل `accounts.json`

## ⚠️ نکته‌ی امنیتی مهم

فایل `accounts.json` که پس از افزودن اکانت‌ها ساخته می‌شود شامل **رشته‌ی نشست (session string)** اکانت‌های تلگرامی توست — دقیقاً هم‌ارزِ رمز عبور آن اکانت‌هاست. این فایل را:
- هرگز در گیت‌هاب یا هر مخزن عمومی آپلود نکن (در `.gitignore` قرار بده)
- فقط روی سروری که به آن اعتماد کامل داری نگه‌دار

## 📋 پیش‌نیازها

- Python نسخه‌ی ۳.۸ یا بالاتر
- کتابخانه‌ی `Telethon`
- یک `API_ID` و `API_HASH` معتبر از [my.telegram.org](https://my.telegram.org)

