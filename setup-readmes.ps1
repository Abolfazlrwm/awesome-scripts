## ✨ امکانات

- 📦 مخزن کانفیگ با افزودن دستی (هر خط = یک کانفیگ)
- 🛒 خرید اشتراک با پرداخت از کیف پول یا کارت‌به‌کارت (تأیید توسط ادمین)
- 🔑 اکانت تست رایگان روزانه
- 🎲 گردونه‌ی شانس (Lucky Wheel) با جایزه‌ی نقدی
- 👑 سیستم نمایندگی با تخفیف ۱۰٪ دائمی برای نمایندگان
- 👥 زیرمجموعه‌گیری و پورسانت معرفی (Referral)
