# 🎨 ربات پستر ایموجی پرمیوم (Cloudflare Worker)

ربات ارسال پست حرفه‌ای به کانال با پشتیبانی کامل از ایموجی‌های پرمیوم و اختصاصی تلگرام (Custom Emoji) — کاملاً رایگان و روی زیرساخت Cloudflare Workers اجرا می‌شود.

![Cloudflare Workers](https://img.shields.io/badge/Cloudflare-Workers-F38020.svg)
![D1 Database](https://img.shields.io/badge/Cloudflare-D1-F38020.svg)
![License](https://img.shields.io/badge/license-MIT-green)

## ✨ امکانات

- ✍️ ارسال حرفه‌ای پست به کانال‌های خودت (متن، عکس، فیلم، فایل)
- 💎 استفاده رایگان از ایموجی‌های پرمیوم داخل متن پست
- 🎯 فرمت‌بندی طبیعی متن بدون دردسر (Bold, Italic, لینک و ...)
- 🆔 پشتیبانی از Custom Emoji با وارد کردن آیدی عددی ایموجی داخل `[ ]`
- 🖥 رابط کاربری تمیز و بدون شلوغی با دکمه‌های شیشه‌ای
- 🌐 حالت عمومی و خصوصی برای ربات (فقط سازنده یا همه‌ی کاربران)
- 🔒 جوین اجباری قابل مدیریت از داخل ربات
- ⚡️ اجرا روی Cloudflare Workers — بدون نیاز به سرور، رایگان و سریع
- 💾 ذخیره‌سازی اطلاعات با Cloudflare D1 (پایگاه‌داده‌ی SQL سرورلس)

## 📋 پیش‌نیازها

- یک اکانت Cloudflare (رایگان)
- یک ربات تلگرام ساخته‌شده با اکانتی که Telegram Premium دارد (الزامی برای استفاده از ایموجی پرمیوم)

## ⚙️ نصب و راه‌اندازی

### گام ۱: ساخت Worker
وارد داشبورد Cloudflare شو → بخش **Workers & Pages** → **Create Worker** → یک Worker جدید بساز و کد فایل `worker.js` را داخلش پیست کن.

### گام ۲: ساخت پایگاه‌داده D1
از بخش **D1** یک پایگاه‌داده‌ی جدید بساز، سپس از تنظیمات Worker (**Settings → Bindings**) آن را با نام `DB` به Worker متصل کن.

### گام ۳: تنظیم متغیرهای محیطی
از مسیر **Settings → Variables and Secrets** این سه مقدار را اضافه کن:

| متغیر | توضیح |
|---|---|
| `BOT_TOKEN` | توکن ربات از [@BotFather](https://t.me/BotFather) — حتماً باید از اکانتی گرفته شود که Telegram Premium دارد |
| `ADMIN_ID` | آیدی عددی ادمین از [@userinfobot](https://t.me/userinfobot) |
| `ADMIN_SECRET` | یک رشته‌ی تصادفی و قوی از حروف انگلیسی و عدد (برای امنیت مسیر راه‌اندازی) |

### گام ۴: راه‌اندازی نهایی
پس از دیپلوی Worker، آدرس زیر را در مرورگر باز کن (به‌جای `<ADMIN_SECRET>` مقدار واقعی را بگذار):

https://your-worker.workers.dev/setup?key=<ADMIN_SECRET>

این مسیر به‌صورت خودکار جداول پایگاه‌داده را می‌سازد و وبهوک تلگرام را تنظیم می‌کند.

### گام ۵: ثبت کانال
یک پست از کانال خودت را برای ربات فوروارد کن تا در لیست کانال‌های تو ثبت شود (ربات باید در کانال ادمین باشد و دسترسی «ارسال و مدیریت پست‌ها» را داشته باشد).

## 💡 آیدی ایموجی پرمیوم را از کجا پیدا کنم؟

می‌توانی از کانال‌های آماده‌ی ایموجی پرمیوم (یا استخراج مستقیم از پیام‌های حاوی ایموجی پرمیوم در تلگرام دسکتاپ) آیدی عددی ایموجی را پیدا کنی، و آن را داخل `[ ]` در متن پست بنویسی — مثلاً: `سلام [5417984163095542602]`

